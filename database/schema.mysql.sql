CREATE TABLE IF NOT EXISTS Clinics (
  ClinicId INT AUTO_INCREMENT PRIMARY KEY,
  ClinicName VARCHAR(150) NOT NULL,
  Location VARCHAR(200) NOT NULL,
  CreatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

